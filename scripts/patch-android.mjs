/**
 * بعد از `npx cap add android` اجرا می‌شود (ورک‌فلوی گیت‌هاب این کار را خودکار انجام می‌دهد):
 *  ۱) پلاگین بومی ذخیره در پوشهٔ Download (MediaStore) را وارد پروژهٔ اندروید می‌کند
 *  ۲) حافظهٔ بیشتر برای مدل صوتی (largeHeap) فعال می‌شود
 *  ۳) آیکون اپ جایگزین آیکون پیش‌فرض می‌شود
 *
 *   node scripts/patch-android.mjs
 */
import fs from "node:fs";
import path from "node:path";

const root = process.cwd();
const PACKAGE = "ir.avasaz.app";
const androidMain = path.join(root, "android", "app", "src", "main");

if (!fs.existsSync(androidMain)) {
  console.error("پوشهٔ android پیدا نشد. اول `npx cap add android` را اجرا کنید.");
  process.exit(1);
}

// 1) native plugin + MainActivity
const javaDir = path.join(androidMain, "java", ...PACKAGE.split("."));
fs.mkdirSync(javaDir, { recursive: true });
for (const file of ["MediaSaverPlugin.java", "MainActivity.java"]) {
  fs.copyFileSync(path.join(root, "android-src", file), path.join(javaDir, file));
  console.log("✓ copied", file);
}

// 2) manifest: more memory for the on-device voice model
const manifestPath = path.join(androidMain, "AndroidManifest.xml");
let manifest = fs.readFileSync(manifestPath, "utf8");
if (!manifest.includes("android:largeHeap")) {
  manifest = manifest.replace("<application", '<application\n        android:largeHeap="true"');
  fs.writeFileSync(manifestPath, manifest);
  console.log("✓ manifest: largeHeap enabled");
}

// 3) launcher icons: one per screen density, generated by scripts/make-icons.mjs
const iconSrc = path.join(root, "android-src", "icons");
const resDir = path.join(androidMain, "res");
if (fs.existsSync(iconSrc) && fs.existsSync(resDir)) {
  let replaced = 0;
  for (const density of fs.readdirSync(iconSrc)) {
    const targetDir = path.join(resDir, `mipmap-${density}`);
    if (!fs.existsSync(targetDir)) continue;
    for (const name of ["ic_launcher.png", "ic_launcher_round.png"]) {
      const from = path.join(iconSrc, density, name);
      if (fs.existsSync(from)) {
        fs.copyFileSync(from, path.join(targetDir, name));
        replaced++;
      }
    }
  }
  // remove adaptive-icon XML so the PNG logos are used on every API level
  const anydpi = path.join(resDir, "mipmap-anydpi-v26");
  if (fs.existsSync(anydpi)) {
    for (const f of fs.readdirSync(anydpi)) {
      if (f.endsWith(".xml")) fs.rmSync(path.join(anydpi, f));
    }
  }
  const bg = path.join(resDir, "values", "ic_launcher_background.xml");
  if (fs.existsSync(bg)) {
    fs.writeFileSync(
      bg,
      `<?xml version="1.0" encoding="utf-8"?>\n<resources>\n    <color name="ic_launcher_background">#06090E</color>\n</resources>\n`,
    );
  }
  console.log(`✓ launcher icons replaced (${replaced} files)`);
}
